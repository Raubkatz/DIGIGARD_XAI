def make_master_summary_dataframe(
    results: Dict[str, Dict[str, Any]],
) -> pd.DataFrame:
    rows: List[Dict[str, Any]] = []

    main_metrics = [
        "accuracy",
        "balanced_accuracy",
        "precision",
        "recall_sensitivity",
        "specificity",
        "f1",
        "mcc",
        "roc_auc",
        "average_precision",
        "brier_score",
        "log_loss",
    ]

    for dataset_key in DATASET_ORDER:
        result = results[
            dataset_key
        ]

        row: Dict[str, Any] = {
            "dataset":
                dataset_key,
            "dataset_display_name":
                result[
                    "display_name"
                ],
            "rows":
                result[
                    "rows"
                ],
            "class_0_rows":
                result[
                    "class_counts"
                ].get(
                    "0",
                    0,
                ),
            "class_1_rows":
                result[
                    "class_counts"
                ].get(
                    "1",
                    0,
                ),
            "balanced_subset_size":
                result[
                    "balanced_subset_size"
                ],
            "balanced_iterations":
                result[
                    "balanced_iterations"
                ],
        }

        for metric_name in main_metrics:
            row[
                f"full_{metric_name}"
            ] = (
                result[
                    "full_metrics"
                ].get(
                    metric_name,
                    np.nan,
                )
            )

            row[
                f"balanced_mean_{metric_name}"
            ] = (
                result[
                    "balanced_metrics_mean"
                ].get(
                    metric_name,
                    np.nan,
                )
            )

            row[
                f"balanced_std_{metric_name}"
            ] = (
                result[
                    "balanced_metrics_std"
                ].get(
                    metric_name,
                    np.nan,
                )
            )

        rows.append(
            row
        )

    return pd.DataFrame(
        rows
    )


