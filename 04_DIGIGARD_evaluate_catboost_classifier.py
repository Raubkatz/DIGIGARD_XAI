def balanced_indices(
    y_true: np.ndarray,
    fraction_minority: float,
    seed: int,
) -> np.ndarray:
    y = np.asarray(
        y_true,
        dtype=int,
    )

    unique_classes, counts = np.unique(
        y,
        return_counts=True,
    )

    if len(unique_classes) != 2:
        raise ValueError(
            "Balanced undersampling requires exactly two classes."
        )

    minority_class = unique_classes[
        np.argmin(counts)
    ]
    majority_class = unique_classes[
        np.argmax(counts)
    ]

    minority_idx = np.flatnonzero(
        y == minority_class
    )

    majority_idx = np.flatnonzero(
        y == majority_class
    )

    n_pick = int(
        round(
            len(minority_idx)
            * fraction_minority
        )
    )

    n_pick = max(
        1,
        min(
            n_pick,
            len(minority_idx),
            len(majority_idx),
        ),
    )

    rng = np.random.default_rng(
        seed
    )

    chosen_minority = rng.choice(
        minority_idx,
        size=n_pick,
        replace=False,
    )

    chosen_majority = rng.choice(
        majority_idx,
        size=n_pick,
        replace=False,
    )

    selected = np.concatenate([
        chosen_minority,
        chosen_majority,
    ])

    rng.shuffle(
        selected
    )

    return selected


def flatten_report_iteration(
    report: Dict[str, Any],
    iteration: int,
) -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []

    for label, values in report.items():
        if isinstance(
            values,
            dict,
        ):
            rows.append({
                "iteration": iteration,
                "label": label,
                "precision":
                    float(
                        values.get(
                            "precision",
                            np.nan,
                        )
                    ),
                "recall":
                    float(
                        values.get(
                            "recall",
                            np.nan,
                        )
                    ),
                "f1-score":
                    float(
                        values.get(
                            "f1-score",
                            np.nan,
                        )
                    ),
                "support":
                    float(
                        values.get(
                            "support",
                            np.nan,
                        )
                    ),
            })

        else:
            rows.append({
                "iteration": iteration,
                "label": label,
                "precision": np.nan,
                "recall": np.nan,
                "f1-score": float(values),
                "support": np.nan,
            })

    return rows


def repeated_balanced_evaluation(
    y_true: np.ndarray,
    probability_class1: np.ndarray,
    threshold: float,
    seed0: int,
) -> Dict[str, Any]:
    """
    Repeatedly evaluate balanced subsets of an already-predicted dataset.

    The model is NOT retrained and probabilities are NOT recomputed.
    """
    y = np.asarray(
        y_true,
        dtype=int,
    )

    p = np.asarray(
        probability_class1,
        dtype=float,
    )

    if len(y) != len(p):
        raise ValueError(
            "Balanced evaluation target/probability length mismatch."
        )

    iteration_metric_rows: List[
        Dict[str, Any]
    ] = []

    classification_report_rows: List[
        Dict[str, Any]
    ] = []

    confusion_matrices: List[
        np.ndarray
    ] = []

    normalized_confusion_matrices: List[
        np.ndarray
    ] = []

    subset_size: Optional[int] = None

    for iteration in range(
        N_BALANCED_ITERATIONS
    ):
        idx = balanced_indices(
            y_true=y,
            fraction_minority=
                BALANCED_MINORITY_FRACTION,
            seed=seed0 + iteration,
        )

        y_i = y[idx]
        p_i = p[idx]

        (
            metrics_i,
            cm_i,
            normalized_cm_i,
            pred_i,
        ) = compute_metrics(
            y_true=y_i,
            probability_class1=p_i,
            threshold=threshold,
        )

        subset_size = int(
            len(idx)
        )

        metric_row = {
            "iteration": iteration,
            "seed": seed0 + iteration,
            "rows": int(len(idx)),
            "class_0_rows":
                int(
                    np.sum(
                        y_i == 0
                    )
                ),
            "class_1_rows":
                int(
                    np.sum(
                        y_i == 1
                    )
                ),
            **metrics_i,
        }

        iteration_metric_rows.append(
            metric_row
        )

        report_i = (
            classification_report_dict(
                y_i,
                pred_i,
            )
        )

        classification_report_rows.extend(
            flatten_report_iteration(
                report_i,
                iteration,
            )
        )

        confusion_matrices.append(
            cm_i.astype(float)
        )

        normalized_confusion_matrices.append(
            normalized_cm_i.astype(float)
        )

    iteration_metrics_df = pd.DataFrame(
        iteration_metric_rows
    )

    all_classification_reports_df = (
        pd.DataFrame(
            classification_report_rows
        )
    )

    numeric_metric_columns = [
        column
        for column in iteration_metrics_df.columns
        if column
        not in {
            "iteration",
            "seed",
        }
        and pd.api.types.is_numeric_dtype(
            iteration_metrics_df[column]
        )
    ]

    metrics_mean = {
        column:
            float(
                iteration_metrics_df[
                    column
                ].mean()
            )
        for column in numeric_metric_columns
    }

    metrics_std = {
        column:
            float(
                iteration_metrics_df[
                    column
                ].std(
                    ddof=1
                )
            )
        for column in numeric_metric_columns
    }

    report_metric_columns = [
        "precision",
        "recall",
        "f1-score",
        "support",
    ]

    report_mean_df = (
        all_classification_reports_df
        .groupby(
            "label",
            sort=False,
        )[report_metric_columns]
        .mean()
        .reset_index()
    )

    report_std_df = (
        all_classification_reports_df
        .groupby(
            "label",
            sort=False,
        )[report_metric_columns]
        .std(
            ddof=1
        )
        .reset_index()
    )

    mean_cm = np.mean(
        np.stack(
            confusion_matrices,
            axis=0,
        ),
        axis=0,
    )

    std_cm = np.std(
        np.stack(
            confusion_matrices,
            axis=0,
        ),
        axis=0,
        ddof=1,
    )

    mean_normalized_cm = np.mean(
        np.stack(
            normalized_confusion_matrices,
            axis=0,
        ),
        axis=0,
    )

    std_normalized_cm = np.std(
        np.stack(
            normalized_confusion_matrices,
            axis=0,
        ),
        axis=0,
        ddof=1,
    )

    return {
        "iterations":
            N_BALANCED_ITERATIONS,
        "minority_fraction":
            BALANCED_MINORITY_FRACTION,
        "subset_size":
            subset_size,
        "metrics_mean":
            metrics_mean,
        "metrics_std":
            metrics_std,
        "mean_confusion_matrix":
            mean_cm,
        "std_confusion_matrix":
            std_cm,
        "mean_normalized_confusion_matrix":
            mean_normalized_cm,
        "std_normalized_confusion_matrix":
            std_normalized_cm,
        "iteration_metrics_df":
            iteration_metrics_df,
        "all_classification_reports_df":
            all_classification_reports_df,
        "classification_report_mean_df":
            report_mean_df,
        "classification_report_std_df":
            report_std_df,
    }


