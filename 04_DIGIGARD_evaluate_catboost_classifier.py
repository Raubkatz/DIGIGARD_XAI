def class_counts(
    y: pd.Series | np.ndarray,
) -> Dict[str, int]:
    counts = pd.Series(
        np.asarray(y, dtype=int)
    ).value_counts().sort_index()

    return {
        str(int(key)): int(value)
        for key, value in counts.items()
    }


def class_fractions(
    y: pd.Series | np.ndarray,
) -> Dict[str, float]:
    fractions = pd.Series(
        np.asarray(y, dtype=int)
    ).value_counts(
        normalize=True
    ).sort_index()

    return {
        str(int(key)): float(value)
        for key, value in fractions.items()
    }


def validate_binary_target(
    series: pd.Series,
    dataset_name: str,
) -> pd.Series:
    numeric = pd.to_numeric(
        series,
        errors="coerce",
    )

    if numeric.isna().any():
        raise ValueError(
            f"{dataset_name}: target '{TARGET}' contains "
            f"{int(numeric.isna().sum())} missing/non-numeric values."
        )

    observed = sorted(
        float(value)
        for value in pd.unique(numeric)
    )

    unexpected = [
        value
        for value in observed
        if value not in {0.0, 1.0}
    ]

    if unexpected:
        raise ValueError(
            f"{dataset_name}: target '{TARGET}' is not binary 0/1. "
            f"Unexpected values: {unexpected}"
        )

    y = numeric.astype(int)

    if y.nunique() != 2:
        raise ValueError(
            f"{dataset_name}: both classes are required. "
            f"Counts: {class_counts(y)}"
        )

    return y


def preprocess_numeric_features(
    df: pd.DataFrame,
    features: List[str],
    dataset_name: str,
) -> Tuple[pd.DataFrame, Dict[str, Any]]:
    """
    Apply the same deterministic numeric preparation used by Stage 03.

    No fitted transformation is performed.
    """
    missing_features = [
        feature
        for feature in features
        if feature not in df.columns
    ]

    if missing_features:
        raise ValueError(
            f"{dataset_name}: missing required model features:\n"
            + "\n".join(missing_features)
        )

    X = df[features].copy()

    coercion_losses: Dict[str, int] = {}

    for column in features:
        original = X[column]

        before_non_missing = int(
            original.notna().sum()
        )

        if pd.api.types.is_numeric_dtype(
            original
        ):
            converted = pd.to_numeric(
                original,
                errors="coerce",
            )
        else:
            text = (
                original
                .astype("string")
                .str.strip()
                .str.replace(
                    ",",
                    ".",
                    regex=False,
                )
            )

            converted = pd.to_numeric(
                text,
                errors="coerce",
            )

        after_non_missing = int(
            converted.notna().sum()
        )

        lost = max(
            0,
            before_non_missing
            - after_non_missing,
        )

        if lost > 0:
            coercion_losses[column] = lost

        X[column] = converted

    X = X.replace(
        [np.inf, -np.inf],
        np.nan,
    )

    preprocessing_report = {
        "dataset": dataset_name,
        "rows": int(len(X)),
        "feature_count": len(features),
        "numeric_coercions_to_nan":
            coercion_losses,
        "total_missing_cells":
            int(X.isna().sum().sum()),
        "rows_with_any_missing_feature":
            int(X.isna().any(axis=1).sum()),
        "rows_with_all_features_missing":
            int(X.isna().all(axis=1).sum()),
        "all_missing_features": [
            column
            for column in features
            if X[column].isna().all()
        ],
    }

    return X, preprocessing_report


