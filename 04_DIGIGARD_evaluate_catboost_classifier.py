def load_model_manifest() -> Dict[str, Any]:
    if not MODEL_MANIFEST.exists():
        raise SystemExit(
            "Stage-03 model manifest not found:\n"
            f"  {MODEL_MANIFEST.resolve()}"
        )

    with MODEL_MANIFEST.open(
        "r",
        encoding="utf-8",
    ) as handle:
        manifest = json.load(handle)

    manifest_target = manifest.get(
        "target"
    )

    manifest_model_type = str(
        manifest.get(
            "model_type",
            "",
        )
    ).strip().upper()

    manifest_run_name = manifest.get(
        "run_name"
    )

    if manifest_target != TARGET:
        raise ValueError(
            "Target mismatch between Stage-04 config and "
            "Stage-03 model manifest:\n"
            f"  Stage 04 TARGET: {TARGET}\n"
            f"  Manifest target: {manifest_target}"
        )

    if manifest_model_type != "CATBOOST":
        raise ValueError(
            "Stage 04 is CatBoost-only.\n"
            f"Loaded Stage-03 model_type: "
            f"{manifest_model_type!r}"
        )

    if manifest_run_name != MODEL_RUN:
        raise ValueError(
            "MODEL_RUN mismatch:\n"
            f"  Stage 04 MODEL_RUN: {MODEL_RUN}\n"
            f"  Manifest run_name:  {manifest_run_name}"
        )

    return manifest


def load_feature_contract() -> List[str]:
    if not MODEL_FEATURES_JSON.exists():
        raise SystemExit(
            "Stage-03 features.json not found:\n"
            f"  {MODEL_FEATURES_JSON.resolve()}"
        )

    with MODEL_FEATURES_JSON.open(
        "r",
        encoding="utf-8",
    ) as handle:
        payload = json.load(handle)

    if isinstance(
        payload,
        list,
    ):
        features = list(payload)

    elif isinstance(
        payload,
        dict,
    ):
        features = list(
            payload.get(
                "features",
                [],
            )
        )

    else:
        raise ValueError(
            "Unsupported Stage-03 features.json format."
        )

    if not features:
        raise ValueError(
            "No features found in Stage-03 feature contract."
        )

    if len(features) != len(set(features)):
        raise ValueError(
            "Duplicate feature names found in Stage-03 feature contract."
        )

    return features


def resolve_threshold(
    manifest: Dict[str, Any],
) -> float:
    if THRESHOLD_OVERRIDE is not None:
        threshold = float(
            THRESHOLD_OVERRIDE
        )
        source = "THRESHOLD_OVERRIDE"

    else:
        threshold = float(
            manifest.get(
                "default_probability_threshold",
                0.50,
            )
        )
        source = (
            "Stage-03 model_manifest.json "
            "default_probability_threshold"
        )

    if not 0.0 < threshold < 1.0:
        raise ValueError(
            f"Resolved threshold must be in (0,1), got {threshold}."
        )

    print(
        f"[THRESHOLD] {threshold:.6g} "
        f"({source})"
    )

    return threshold


